def build_cases() -> tuple[CustodyCase, ...]:
    """Return every case, executed ones first.

    Returns
    -------
    tuple
        The whole corpus.

    """
    return _executed_cases() + _design_vector_cases()


def case_manifest_entry(case: CustodyCase) -> dict[str, Any]:
    """Return the manifest row for one case.

    Parameters
    ----------
    case
        The case to describe.

    Returns
    -------
    dict
        Manifest fields, including the fixture digest when the case has bytes.

    """
    entry: dict[str, Any] = {
        "case_id": case.case_id,
        "family": case.family,
        "producer": case.producer,
        "reader": case.reader,
        "expectation": case.expectation,
        "status": case.status,
        "rationale": case.rationale,
    }
    if case.payload is None:
        entry["fixture"] = None
        entry["fixture_sha256"] = None
    else:
        entry["fixture"] = f"{case.case_id}.json"
        entry["fixture_sha256"] = scp.digest_stable_core_payload(case.payload)
    return entry


def build_manifest(cases: tuple[CustodyCase, ...]) -> dict[str, Any]:
    """Return the full corpus manifest.

    Parameters
    ----------
    cases
        Cases to describe.

    Returns
    -------
    dict
        The manifest, cases in the given order.

    """
    return {
        "schema": CORPUS_SCHEMA,
        "companion_schema": vectors.COMPANION_SCHEMA,
        "companion_module": COMPANION_MODULE,
        "model_schema_version": scp.STABLE_CORE_MODEL_SCHEMA_VERSION,
        "design_vectors_are_unexecuted": True,
        "cases": [case_manifest_entry(case) for case in cases],
    }


def validate_manifest_schema(manifest: Mapping[str, Any]) -> str:
    """Return the manifest schema, refusing a superseded coded name.

    Parameters
    ----------
    manifest
        A parsed corpus manifest.

    Returns
    -------
    str
        The accepted schema identifier.

    Raises
    ------
    ValueError
        If the schema is a superseded internally-coded name, or is unknown.

    """
    schema = manifest.get("schema")
    if schema in SUPERSEDED_CORPUS_SCHEMAS:
        raise ValueError(
            f"corpus schema {schema!r} encodes an internal planning identifier and is "
            f"superseded by {CORPUS_SCHEMA!r}; regenerate the corpus"
        )
    if schema != CORPUS_SCHEMA:
        raise ValueError(f"unknown corpus schema {schema!r}; expected {CORPUS_SCHEMA!r}")
    return CORPUS_SCHEMA


def write_corpus(destination: Path) -> dict[str, Any]:
    """Write fixtures and manifest under ``destination``.

    Parameters
    ----------
    destination
        Directory to populate; created if absent.

    Returns
    -------
    dict
        The manifest that was written.

    """
    destination.mkdir(parents=True, exist_ok=True)
    cases = build_cases()
    for case in cases:
        if case.payload is None:
            continue
        body = scp.canonical_json_bytes(case.payload)
        (destination / f"{case.case_id}.json").write_bytes(body)
    manifest = build_manifest(cases)
    (destination / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return manifest


def main(argv: list[str] | None = None) -> int:
    """Write the corpus to the requested directory.

    Parameters
    ----------
    argv
        Command-line arguments; defaults to :data:`sys.argv`.

    Returns
    -------
    int
        Process exit status, zero on success.

    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("destination", type=Path)
    arguments = parser.parse_args(argv)
    manifest = write_corpus(arguments.destination)
    sys.stdout.write(f"{len(manifest['cases'])} cases written\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
