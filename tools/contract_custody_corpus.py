# SCPN Quantum Control — versioned contract custody corpus
"""Build the accept/reject corpus for versioned record custody.

Two kinds of case live here and they must never be quoted as one another.

An **executed** case names a production reader that exists today and is invoked
with real inputs; its expected outcome is the outcome that reader produces. A
**design vector** is a concrete proposed input for the semantic companion record
that is specified but not built; its expected semantics are stated and nothing
is executed. Labelling a design vector as executed would be the same overclaim
as citing an import as conformance.

Fixtures are generated by calling the producers rather than hand-written,
because a digest recorded without the bytes it describes cannot be checked
afterwards. The corpus is written once, checked in, and re-derived by its owner
tests so that producer drift surfaces as a failure instead of a surprise.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

from scpn_quantum_control import stable_core_product as scp
from tools import contract_custody_design_vectors as vectors

CORPUS_SCHEMA: Final[str] = "contract_custody_corpus.v1"
"""Schema of the manifest this module writes."""

SUPERSEDED_CORPUS_SCHEMAS: Final = frozenset({"core_g02_contract_corpus.v1"})
"""Manifest schemas that must be refused rather than read.

The first corpus schema encoded an internal planning identifier, which the
descriptive-naming directive forbids on any public or serialised surface. A
reader that silently accepted the old name would keep that identifier alive in
stored artefacts, so it is refused by name.
"""

COMPANION_MODULE: Final[str] = "scpn_quantum_control.semantic_record"
"""Planned owner of the semantic companion; absent from source today."""

EXECUTED: Final[str] = "executed"
"""A production reader was invoked and its outcome is the expected outcome."""

DESIGN_VECTOR: Final[str] = "design_vector"
"""A concrete proposed input, specified and deliberately not executed."""


@dataclass(frozen=True)
class CustodyCase:
    """One accept/reject case with its reader and its evidence class.

    Parameters
    ----------
    case_id
        Stable identifier, used as the fixture filename stem.
    family
        Which mapped contract family the case exercises.
    producer
        Module-qualified identity of the producing type or callable.
    reader
        Module-qualified reader whose behaviour the case pins. For a design
        vector this is the proposed reader, which does not exist yet.
    expectation
        ``accept`` or ``reject``.
    status
        :data:`EXECUTED` or :data:`DESIGN_VECTOR`.
    rationale
        Why this case exists, in one sentence.
    payload
        The fixture body, or ``None`` when the case pins behaviour rather than
        bytes.

    """

    case_id: str
    family: str
    producer: str
    reader: str
    expectation: str
    status: str
    rationale: str
    payload: Mapping[str, Any] | None


def raw_experiment_record() -> dict[str, Any]:
    """Return the serialised demonstration experiment envelope.

    Returns
    -------
    dict
        The v2 envelope exactly as the production serialiser emits it.

    """
    return scp.serialise_experiment(scp.build_demo_experiment())


def _with_companion_key() -> dict[str, Any]:
    """Return a v2 envelope with a companion key wrongly added inside it.

    Returns
    -------
    dict
        An envelope the v2 reader must refuse as key drift.

    """
    envelope = raw_experiment_record()
    envelope["scientific_semantics"] = {"schema": vectors.COMPANION_SCHEMA}
    return envelope


def _with_unknown_model_major() -> dict[str, Any]:
    """Return a v2 envelope carrying an unreadable model schema version.

    Returns
    -------
    dict
        An envelope whose model major the reader cannot know.

    """
    envelope = raw_experiment_record()
    envelope["schema_version"] = "stable_core.experiment_model.v3"
    return envelope


def _with_mismatched_kind() -> dict[str, Any]:
    """Return an experiment envelope relabelled as a problem.

    Returns
    -------
    dict
        An envelope whose kind contradicts its body.

    """
    envelope = raw_experiment_record()
    envelope["kind"] = "problem"
    return envelope


